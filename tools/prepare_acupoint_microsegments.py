"""Prepare the user's new stance for two short H3 motion probes, without submitting."""
from pathlib import Path
import copy
import hashlib
import json
import shutil
import sys

from PIL import Image

ROOT = Path('D:/AI/minimax-h3-minimal')
PROJECT = Path(__file__).resolve().parents[1]
BATCH = ROOT / 'action-batches/acupoint-microsegments-20261109'
REVIEW = PROJECT / 'artifacts/acupoint-microsegments-review'
SOURCE = Path('C:/Users/51440/Downloads/像素武士绿幕姿态对齐版.png')


def save(path, data):
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf8')


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    if (BATCH / 'batch.json').exists():
        raise FileExistsError('Preserve existing batch; preparation does not overwrite jobs.')
    BATCH.mkdir(parents=True, exist_ok=True)
    (REVIEW / 'reference').mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOURCE, REVIEW / 'reference/user-original.png')
    source = Image.open(SOURCE).convert('RGB')
    assert source.size == (1024, 2048)
    resized = source.resize((352, 704), Image.Resampling.LANCZOS)
    canvas = Image.new('RGB', (512, 768), (0, 255, 0))
    canvas.paste(resized, (80, 32))
    reference = REVIEW / 'reference/anchor-512x768.png'
    canvas.save(reference)
    prepared = ROOT / 'ComfyUI_windows_portable/ComfyUI/input/H3_acupoint_micro_20261109_anchor.png'
    shutil.copy2(reference, prepared)
    source_record = dict(source=str(SOURCE), source_sha256=sha(SOURCE), prepared=str(prepared),
                         input_sha256=sha(prepared), source_size=[1024, 2048], uniform_scale=11/32,
                         resized_size=[352, 704], paste_offset=[80, 32], canvas=[512, 768],
                         crop=False, stretch=False, per_frame_alignment=False,
                         only_image_reference='User new green-screen stance',
                         original_game_images_or_video_input=False,
                         final_full_action_target='Same prepared user image, only on eventual recovery segment',
                         intermediate_poses='Generated by H3; no hand-authored pose-image anchors')
    save(REVIEW / 'reference/source.json', source_record)
    sys.path.insert(0, str(ROOT))
    from run_pixel import make_prompt
    base = json.loads((ROOT / 'action-batches/acupoint-right-20261107-v5b/workflow.json').read_text(encoding='utf8'))
    for count in (5, 22):
        folder = BATCH / f'probe-{count:02d}'
        folder.mkdir()
        prefix = f'H3_acupoint_micro_20261109_probe{count:02d}'
        prompt = f'''How the reference pictures align with the target video: Picture 1 aligns with the first frame.

integrated_multimodal_description: [Shot 1] A very short {count / 24:.3f}-second opening fragment of a martial-arts movement. The single man in Picture 1 makes ONE SMALL continuous preparation, starting immediately: soften both knees slightly and settle the pelvis a little lower, begin turning the waist and shoulders a few degrees toward screen right, and lift his anatomical right hand (the closed hand at screen left in Picture 1) slightly toward his right ribs. His other hand stays relaxed and open, with a small natural counterbalancing motion. Both feet stay in their starting contact positions during this initial weight-settling fragment. His face and eyes keep looking toward the target at screen right. End partway into the preparation, ready to continue. This fragment contains only this small beginning, without the jab or recovery.

Use exactly the same character design and body build throughout: unchanged head size, short neck, shoulder breadth, torso thickness, arm and leg lengths, limb thickness, facial features, clothing, belt and sandals. Bending the knees changes pose, never anatomy or image scale. Fixed full-body camera, constant framing and magnification. Natural connected joints and continuous clothing overlap. Crisp illustrated pixel outlines, steady colors and lighting. Keep both eyes with visible dark pupils. Preserve the plain bright green background. All hair, hands and feet remain visible inside the canvas. One character only, empty hands, no scenery, effects or camera motion.

overall_soundscape: None.
non_diegetic_music: None.'''
        (folder / 'prompt.txt').write_text(prompt, encoding='utf8')
        wf = copy.deepcopy(base)
        removed_links = {link[0] for link in wf['links'] if link[3] == 131 and link[4] == 3}
        wf['links'] = [link for link in wf['links'] if link[0] not in removed_links]
        for node in wf['nodes']:
            for inp in node.get('inputs', []):
                if inp.get('link') in removed_links:
                    inp['link'] = None
            for out in node.get('outputs', []):
                out['links'] = [v for v in (out.get('links') or []) if v not in removed_links]
            if node['id'] == 131:
                node['widgets_values'] = [prompt, 512, 768, count]
                node['widgets_values_named'] = dict(prompt=prompt, width=512, height=768, length=count)
                node['title'] = f'Small preparation only; {count} frames; first image only'
            elif node['id'] == 142:
                node['widgets_values'] = [prepared.name, 'image']
                node['title'] = 'User stance; single uniform resize and green padding'
            elif node['id'] == 143:
                node['widgets_values'] = [prefix + '/frame']
                node['title'] = 'Preserve every original output frame'
            elif node['id'] == 92:
                node['widgets_values'] = ['video/' + prefix, 'mp4', 'h264']
                node['widgets_values_named'] = {'filename_prefix': 'video/' + prefix, 'format': 'mp4', 'format.codec': 'h264'}
        api = make_prompt(wf, 512, count, 8, prefix, 768)
        assert 'last_frame' not in api['131']['inputs']
        assert api['131']['inputs']['first_frame'] == ['142', 0]
        save(folder / 'workflow.json', wf)
        save(folder / 'source.json', source_record)
        save(folder / 'job.json', dict(output_prefix=prefix, width=512, height=768, frames=count,
             fps=24, steps=8, seed=42, direction=f'probe-{count:02d}', action='small_preparation_only',
             source=source_record, client_id=prefix, prompt=api))
    save(BATCH / 'batch.json', dict(status='prepared', runtime_root=str(ROOT),
         probes=[5, 22], source=source_record, user_approved=False, godot_integrated=False))
    shutil.copy2(ROOT / 'action-batches/rest-rise-right-20261108-v2-vram11/manage_comfy.ps1', BATCH / 'manage_comfy.ps1')
    print(str(BATCH))
    print(str(reference))


if __name__ == '__main__':
    main()
