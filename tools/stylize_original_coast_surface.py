"""Sparse, filtered mineral fields from CC0 input; original model/UV and authored lines."""
from pathlib import Path
import runpy,json,shutil
import numpy as np
from PIL import Image
import cv2
R=Path(__file__).resolve().parents[1];A=R/'assets/original_coastal_rock';O=R/'artifacts/original-shore-review'
runpy.run_path(str(R/'tools/paint_original_coastal_rock_planes.py'))
source=A/'sources';source.mkdir(exist_ok=True)
for name in ['rock_boulder_cracked-diffuse.jpg','rock_boulder_cracked-info.json','polyhaven-license.html']:
    candidate=O/'material-search'/name
    if candidate.exists():shutil.copy2(candidate,source/name)
    assert (source/name).exists(),name
im=np.array(Image.open(source/'rock_boulder_cracked-diffuse.jpg').convert('RGB').resize((256,256),Image.Resampling.LANCZOS))
# Eliminate photographic grains before extracting low-frequency mineral structure.
for _ in range(3):im=cv2.bilateralFilter(im,13,35,9)
gray=cv2.cvtColor(im,cv2.COLOR_RGB2GRAY).astype(np.float32)
gray=cv2.GaussianBlur(gray,(0,0),1.6)
gray=(gray-np.median(gray))/26
gray=np.clip(np.round(gray*2)/2,-2,1.5)
photo=np.array(Image.open(A/'warm_rock_sides.png').convert('RGB')).astype(np.float32)
mask_preview=Image.new('RGB',(1024,512))
for i in range(16):
    g=np.rot90(gray,i%4);g=np.roll(np.roll(g,31*i,axis=1),47*i,axis=0)
    g=cv2.resize(g,(1024,512),interpolation=cv2.INTER_NEAREST)
    # Keep much of each plane quiet; broad pigment variation, sparse fissure washes.
    u=np.linspace(0,1,1024)[None,:];v=np.linspace(0,1,512)[:,None]
    mask=.28+.72*np.clip(np.sin(u*9+i*.7)*np.cos(v*5+i*.4),0,1)
    deviation=np.where(g<-.5,g*11,g*6)*mask
    tile=photo[(i//4)*512:(i//4+1)*512,(i%4)*1024:(i%4+1)*1024]
    tile+=deviation[:,:,None]*np.array([.95,.90,.85])[None,None,:]
    if i==1:mask_preview=Image.fromarray(np.uint8(np.clip(tile,0,255)))
Image.fromarray(np.uint8(np.clip(photo,0,255))).save(A/'warm_rock_sides.png')
mask_preview.save(O/'surface-paint-detail.png')
